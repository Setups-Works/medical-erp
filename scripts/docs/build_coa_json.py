"""Generates contracts/reference-data/chart-of-accounts.v1.json from the tables in
docs/architecture/CHART_OF_ACCOUNTS.md (the doc is the source; never edit the JSON by hand).
Run: python3 scripts/docs/build_coa_json.py"""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
md = (ROOT / "docs/architecture/CHART_OF_ACCOUNTS.md").read_text()

def table(heading):
    lines = md.split("\n")
    i = next(k for k, l in enumerate(lines) if l.startswith(heading))
    rows, started = [], False
    for l in lines[i + 1:]:
        if l.startswith("|"):
            started = True
            c = [x.strip() for x in l.strip("|").split("|")]
            if set("".join(c)) <= set("-: "):
                continue
            rows.append(c)
        elif started:
            break
    return rows[1:]  # drop header

code = lambda s: s.strip("`")
groups = table("## Default groups")
name2code = {g[1]: code(g[0]) for g in groups}
G = [{"systemCode": code(c), "name": n, "parent": None if p == "—" else name2code[p],
      "nature": nat.upper(), "affectsGrossProfit": gp == "✓"} for c, n, p, nat, gp in groups]
L = [{"systemCode": code(c), "name": n, "group": name2code[g], "usedBy": u} for c, n, g, u in table("## Default ledgers")]
codes = [x["systemCode"] for x in G + L]
if len(codes) != len(set(codes)):
    sys.exit("duplicate system codes")
out = {
    "version": 1,
    "status": "DRAFT: confirm with a CA before P5 (docs/compliance/COMPLIANCE.md)",
    "source": "docs/architecture/CHART_OF_ACCOUNTS.md (generated by scripts/docs/build_coa_json.py)",
    "rules": {
        "systemItemsDeletable": False,
        "systemItemsRenamable": True,
        "partyLedgers": {"supplier": "SUNDRY_CREDITORS", "customer": "SUNDRY_DEBTORS"},
        "splitByGstRateSetting": "accounting.split_by_gst_rate",
    },
    "groups": G,
    "ledgers": L,
}
dst = ROOT / "contracts/reference-data/chart-of-accounts.v1.json"
dst.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")
print(f"{len(G)} groups, {len(L)} ledgers -> {dst.relative_to(ROOT)}")
