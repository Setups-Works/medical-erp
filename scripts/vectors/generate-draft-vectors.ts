/**
 * Writes the FIRST, DRAFT set of calculation test vectors into contracts/test-vectors/ (format: contracts/AGENTS.md).
 *   cd project-management && npx tsx ../scripts/vectors/generate-draft-vectors.ts
 *
 * Expected values are computed by the MENO Hub teaching engine (project-management/src/lib/learn/invoice.ts), which
 * mirrors docs/architecture/CALCULATIONS.md §2–§5. That makes them a starting point, not truth: every case carries
 * "status": "draft" until Prakalya checks it by hand and, for rules marked ⚠, a CA confirms it. Only then may the
 * Java and offline engines treat it as the contract. Rates are illustrative; real rates come from hsn_tax.
 */
import fs from "node:fs";
