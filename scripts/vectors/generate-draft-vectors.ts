import { calcInvoice, type LineIn, type PriceMode } from "../../project-management/src/lib/learn/invoice";
import { fmt, type Money } from "../../project-management/src/lib/learn/money";

const OUT = path.resolve(__dirname, "../../contracts/test-vectors");
const S = (v: Money, dp = 4) => fmt(v, dp).replace(/,/g, "").replace("−", "-");
const party = (code: string) => ({ name: "x", address: "x", state: "x", stateCode: code });

type Case = { name: string; featureId: string; mode: PriceMode; intraState: boolean; lines: Omit<LineIn, "item" | "hsn">[]; note?: string };

function vector(c: Case) {
  const inv = calcInvoice({
    kind: "Tax invoice",
    number: "v",
    date: "v",
    mode: c.mode,
    seller: party("33"),
    buyer: party(c.intraState ? "33" : "29"),
    lines: c.lines.map((l, i) => ({ item: `item ${i + 1}`, hsn: "3004", ...l })),
  });
  return {
    name: c.name,
    featureId: c.featureId,
    status: "draft",
    source: "Generated by scripts/vectors/generate-draft-vectors.ts from CALCULATIONS.md §2–§5; NOT yet confirmed by Prakalya / CA",
    ...(c.note ? { note: c.note } : {}),
    input: {
      mode: c.mode,
      intraState: c.intraState,
      lines: c.lines.map((l) => ({
        rate: l.rate,
        qty: l.qty,
        ...(l.free ? { freeQty: l.free } : {}),
        ...(l.freeLoose ? { freeLooseUnits: l.freeLoose, unitsPerPack: l.unitsPerPack } : {}),
        ...(l.schemePct ? { schemePct: l.schemePct } : {}),
        discountPct: l.discPct ?? "0",
        gstRate: l.gstPct,
      })),
    },
    expected: {
      lines: inv.lines.map((l) => ({ gross: S(l.gross), scheme: S(l.scheme), discount: S(l.disc), taxable: S(l.taxable), gst: S(l.gst, 2), cgst: S(l.cgst, 2), sgst: S(l.sgst, 2), igst: S(l.igst, 2), total: S(l.total) })),
      taxable: S(inv.taxable),
      cgst: S(inv.cgst, 2),
      sgst: S(inv.sgst, 2),
      igst: S(inv.igst, 2),
      total: S(inv.total),
      roundOff: S(inv.roundOff, 2),
      grandTotal: S(inv.grandTotal, 2),
    },
  };
}

