"use client";

import { ArrowLeft, ExternalLink } from "lucide-react";
import Link from "next/link";
import { useEffect, useState } from "react";
import { PageHeader } from "@/components/page";

/** Follows the Hub's light / dark switch (the `dark` class on <html>) so the guide matches it. */
function useHubTheme(): "dark" | "light" {
  const [theme, setTheme] = useState<"dark" | "light">("light");
  useEffect(() => {
    const read = () => setTheme(document.documentElement.classList.contains("dark") ? "dark" : "light");
    read();
    const obs = new MutationObserver(read);
    obs.observe(document.documentElement, { attributes: true, attributeFilter: ["class"] });
    return () => obs.disconnect();
  }, []);
  return theme;
}

/** Shows a static guide from public/guide/ (generated by scripts/docs/build_*_guide.py) inside the Hub. */
export function GuideFrame({ src, title, subtitle }: { src: string; title: string; subtitle: string }) {
  const theme = useHubTheme();
  const url = `${src}?theme=${theme}`;
  return (
    <div className="mx-auto max-w-[1240px]">
      <PageHeader
        title={title}
        subtitle={subtitle}
        actions={
          <div className="flex flex-wrap gap-2">
            <Link href="/learn" className="flex h-8 items-center gap-1.5 rounded-ctl px-3 text-[13px] text-ink-2 shadow-[inset_0_0_0_1px_var(--line-2)] hover:bg-hover">
              <ArrowLeft className="size-3.5" />
              Lessons
            </Link>
            <a href={url} target="_blank" rel="noreferrer" className="flex h-8 items-center gap-1.5 rounded-ctl bg-ink px-3 text-[13px] font-medium text-paper hover:opacity-90">
              <ExternalLink className="size-3.5" />
              Open full screen
            </a>
          </div>
        }
      />
      <iframe key={theme} src={url} title={title} className="h-[calc(100dvh-190px)] min-h-[560px] w-full rounded-tile bg-raised shadow-[inset_0_0_0_1px_var(--line)]" />
    </div>
  );
}
